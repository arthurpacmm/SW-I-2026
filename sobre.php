    <section id="conteudo">
        <h2>Mecânicas Principais de Jogo</h2>
        <ol>
            <li><strong>Quests Narrativas:</strong> Ao contrário dos RPGs comuns que pedem apenas para "matar 10 monstros", as missões de Wynncraft são focadas em história, quebra-cabeças complexos, parkour e mecânicas únicas.</li>
            <li><strong>Dungeons (Calabouços):</strong> Instâncias espalhadas pelo mundo que exigem uma "Chave de Dungeon" para entrar. Elas contam com chefes com mecânicas de fases e recompensam o jogador com fragmentos para comprar equipamentos poderosos.</li>
            <li><strong>Profissões (Gathering & Crafting):</strong> Você pode coletar recursos (Mineração, Pesca, Lenhador, Agricultura) e refiná-los para criar suas próprias armas, armaduras, poções e pergaminhos sob medida.</li>
            <li><strong>Guerra de Guildas (Territory Wars):</strong> No endgame, as guildas de jogadores disputam o controle dos territórios do mapa global em batalhas estratégicas para dominar bônus de produção e XP.</li>
        </ol>
