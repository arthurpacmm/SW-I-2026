    <section id="sobre">
        <h2>Sobre o Servidor</h2>
        <p>Fundado em 2013, o <strong>Wynncraft</strong> transformou completamente os limites do Minecraft tradicional. Sem a necessidade de instalar nenhum mod externo — utilizando apenas um <em>Resource Pack</em> customizado do próprio servidor —, ele entrega uma experiência completa de RPG de escala massiva. O jogo conta com dublagem parcial, trilha sonora original imersiva, milhares de itens com atributos únicos e uma comunidade ativa de milhares de jogadores.</p>
    </section>

    <section id="provincias">
        <h2>O Mundo: Províncias e Exploração</h2>
        <p>O mapa do Wynncraft possui mais de 4.000 × 4.000 blocos de extensão, repleto de segredos, cavernas escondidas e biomas detalhados. A jornada do jogador é dividida entre continentes e arquipélagos:</p>
        <ul>
            <li><strong>Província de Wynn:</strong> Onde o jogo começa. Uma terra medieval de fantasia clássica, florestas densas, desertos e planícies, constantemente ameaçada por forças que emergem de um <em>portal</em>.</li>
            <li><strong>Província de Gavel:</strong> O reino dos Aldeões. Um continente focado em alta fantasia, montanhas colossais, florestas mágicas e tecnologia baseada em pedras preciosas. É o lar do conteúdo de nível médio a avançado.</li>
            <li><strong>Província de Fruma:</strong> Atual área endgame, a província mais importante para a história do jogo, já que seu personagem vem de lá. É composta por cinco zonas diferentes. </li>
            <li><strong>The Silent Expanse (A Expansão Silenciosa):</strong> A zona de endgame sombria, onde a Corrupção tem origem, composta por florestas macabras e montanhas sombrias, além de uma cidade em ruínas.</li>
        </ul>
    </section>

